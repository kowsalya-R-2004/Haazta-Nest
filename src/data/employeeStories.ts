export const getEmployeeStories = (lang: Language): EmployeeStory[] => {
  const currentList = STORIES_BY_LANG[lang] || STORIES_BY_LANG.en;
  const fallbackList = STORIES_BY_LANG.en;

  return currentList.map((item, index) => {
    const fallbackItem = fallbackList[index] || item;
    return {
      id: item.id || fallbackItem.id,
      name: item.name || fallbackItem.name,
      category: item.category || fallbackItem.category,
      quote: item.quote || fallbackItem.quote,
      avatar: AVATARS[index] || AVATARS[0]
    };
  });
};
